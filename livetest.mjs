import { chromium } from "playwright";
const U="https://kittokatsugo.github.io/potolki-landing/";
const b = await chromium.launch();
const p = await b.newPage({viewport:{width:1440,height:900}});
const errs=[]; p.on("pageerror",e=>errs.push(e.message));
await p.goto(U,{waitUntil:"networkidle",timeout:60000});
console.log("title:", (await p.title()).slice(0,60));
console.log("JS ошибки:", errs.length ? errs.join(" | ") : "нет");
console.log("h1:", await p.locator("h1").count());
await p.locator("#quizOptions .opt").nth(1).click(); await p.waitForTimeout(400);
const tl=await p.locator("#quizOptions .opt").allTextContents();
await p.locator("#quizOptions .opt").nth(tl.findIndex(t=>t.includes("Глянцевый"))).click(); await p.waitForTimeout(400);
const ll=await p.locator("#quizOptions .opt").allTextContents();
await p.locator("#quizOptions .opt").nth(ll.findIndex(t=>t.includes("4 светильника"))).click(); await p.waitForTimeout(600);
console.log("квиз итог:", await p.locator("#quizSum").textContent());
await p.screenshot({path:"screens/pages-live.png", fullPage:false});
const m = await b.newPage({viewport:{width:375,height:812}});
await m.goto(U,{waitUntil:"networkidle",timeout:60000});
console.log("375 scrollWidth:", await m.evaluate(()=>document.documentElement.scrollWidth));
await b.close();
